"""Theme-aware post figures: the shared colour tokens and the render-time inliner.

ADR-0005 records the decision. In short: a post figure that carries the token
block below is inlined into the post HTML at render time instead of being
loaded through ``<img>``, so the CSS custom properties the site sets for its
light and dark themes reach the figure's fills and strokes. A figure without
the block still renders as ``<img>``, unchanged.

Every migrated SVG carries ``token_style_block()`` verbatim. Inside that block
the tokens are declared on ``svg:root``, which only matches when the SVG is
its own document (opened directly or loaded through ``<img>``); there the
figure follows the OS colour scheme. Inlined, the same selector matches
nothing and the page's values, keyed off the theme class Reflex puts on
``<html>``, win.

To migrate a figure, see ``scripts/theme_figure.py`` and ADR-0005.
"""

import html
import re
from pathlib import Path

ASSETS_DIR = Path(__file__).resolve().parent.parent / "assets"

# Token values per theme. Text-bearing tokens hold WCAG AA 4.5:1 against
# ``bg``; ``grid`` holds the 3:1 AA ratio for non-text graphics; ``ink`` holds
# 4.5:1 against every ``*-soft`` fill, which is the only text allowed on them.
# tests/test_figure_tokens.py computes all of these.
