TEXT_TOKENS = ("ink", "muted", "accent-1", "accent-2", "accent-3", "good", "bad")
GRAPHIC_TOKENS = ("grid",)
SOFT_TOKENS = (
    "accent-1-soft",
    "accent-2-soft",
    "accent-3-soft",
    "good-soft",
    "bad-soft",
    "muted-soft",
)

TOKEN_BLOCK_MARKER = "fig-tokens v1"

_FIGURE_LINE = re.compile(r"^!\[(?P<alt>.*)\]\(/(?P<name>[\w.-]+\.svg)\)\s*$")
_FENCE = re.compile(r"^\s*(```|~~~)")


def _declarations(mode: str) -> str:
    return " ".join(f"--fig-{k}: {v};" for k, v in FIGURE_TOKENS[mode].items())


def token_style_block() -> str:
    """Return the exact ``<style>`` element every migrated SVG carries."""
    return (
        f"<style>/* {TOKEN_BLOCK_MARKER}: generated by "
        "src/alberto_codes_site/figures.py, do not edit */\n"
        f"    svg:root {{ {_declarations('light')} }}\n"
        "    @media (prefers-color-scheme: dark) {\n"
        f"      svg:root {{ {_declarations('dark')} }}\n"
        "    }\n"
        "  </style>"
    )


def figure_page_style() -> dict:
    """Return the page CSS that sets the tokens from the site's theme class."""

    def as_vars(mode: str) -> dict[str, str]:
        return {f"--fig-{k}": v for k, v in FIGURE_TOKENS[mode].items()}

    return {
        "& .post-figure": {
            **as_vars("light"),
            "margin": "1.5em 0",
        },
        ".dark & .post-figure": as_vars("dark"),
        "& .post-figure svg": {
            "display": "block",
            "max_width": "100%",
            "height": "auto",
            # Mermaid renders cap their own width below the column; centre them.
            "margin_inline": "auto",
        },
    }


def uses_tokens(svg_text: str) -> bool:
    """Return True when an SVG carries the current shared token block."""
    return token_style_block() in svg_text


def inline_figure_html(name: str, alt: str) -> str | None:
    """Return the inlined markup for a token-carrying figure, else None."""
    path = ASSETS_DIR / name
    if not path.is_file():
        return None
    svg = path.read_text()
    if not uses_tokens(svg):
        return None
    svg = re.sub(r"^\s*<\?xml[^>]*\?>\s*", "", svg)
    label = html.escape(alt, quote=True)
    return f'<div class="post-figure" role="img" aria-label="{label}">{svg}</div>'


def split_figures(body: str) -> list[tuple[str, str]]:
    """Split a post body into markdown runs and inlined theme-aware figures.

    Only an image line that stands alone as its own paragraph, outside any
    fenced code block, is lifted out; everything else stays markdown, so an
    un-migrated figure keeps rendering as ``<img>``.

    Returns:
        A list of ``("markdown", text)`` and ``("figure", html)`` pairs, in order.
    """
    lines = body.split("\n")
    segments: list[tuple[str, str]] = []
    pending: list[str] = []
    in_fence = False
    for i, line in enumerate(lines):
        if _FENCE.match(line):
            in_fence = not in_fence
        match = None if in_fence else _FIGURE_LINE.match(line)
        standalone = (i == 0 or not lines[i - 1].strip()) and (
            i == len(lines) - 1 or not lines[i + 1].strip()
        )
        figure = (
            inline_figure_html(match["name"], match["alt"])
            if match and standalone
            else None
        )
        if figure is None:
            pending.append(line)
            continue
        if "\n".join(pending).strip():
            segments.append(("markdown", "\n".join(pending)))
        pending = []
        segments.append(("figure", figure))
    if "\n".join(pending).strip():
        segments.append(("markdown", "\n".join(pending)))
    return segments
